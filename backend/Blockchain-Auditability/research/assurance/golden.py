"""Golden vectors: inputs and the Python engine's outputs, which tests/goldenVectors.test.js
replays through the JavaScript engine. Any divergence between the two engines fails CI.

    uv run python -m assurance.golden [--policy path/to/policy.json]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from . import config
from .engine import assess, policy_hash_v2

RULES = ["score_below_step_up_threshold", "score_above_step_up_threshold", "score_above_block_threshold",
         "rate_limit_step_up", "rate_limit_block", "ip_reputation_step_up", "amount_hard_block",
         "concept_drift_step_up", "an_unlisted_rule"]
TYPES = ["PORTFOLIO_WITHDRAWAL", "PORTFOLIO_REBALANCE", "PAYMENT", "TRANSFER", "LOAN_DISBURSEMENT", "SOMETHING_ELSE"]


def random_inputs(n: int, seed: int) -> list[dict]:
    rng = np.random.default_rng(seed)
    out = []
    for _ in range(n):
        signals: dict = {}
        k = int(rng.integers(0, 4))                       # 0 or 1 model -> degraded disagreement
        if k:
            signals["modelScores"] = {f"m{i}": round(float(rng.random()), 4) for i in range(k)}
        if rng.random() < 0.8:
            signals["rules"] = [r for r in RULES if rng.random() < 0.15]
        validation = rng.random()
        if validation < 0.45:
            signals.update(benchmarkModel=True, sourceModelVersion="fraud-bundle-2026-10")
        elif validation < 0.7:
            signals.update(benchmarkModel=False, sourceModelVersion="heuristic-untrained")
        elif validation < 0.8:
            signals.update(benchmarkModel=True, sourceModelVersion="unregistered")
        out.append({
            "riskScore": round(float(rng.random() * 100), 2),
            "confidence": int(rng.integers(0, 101)),
            "amount": round(float(np.exp(rng.random() * np.log(2e6))) + 1, 2),
            "transactionType": TYPES[int(rng.integers(0, len(TYPES)))],
            "signals": signals,
        })
    return out


def write(policy_file: Path, out_file: Path, n: int = 400, seed: int = config.SEED) -> dict:
    policy = json.loads(policy_file.read_text(encoding="utf-8"))
    doc = policy["document"]
    cases = [{"input": i, "expected": assess(i, doc)} for i in random_inputs(n, seed)]
    payload = {
        "description": "Generated by research/assurance/golden.py; replayed through the JavaScript engine by tests/goldenVectors.test.js.",
        "policyFile": policy_file.name,
        "policyHash": policy_hash_v2(doc),
        "policy": doc,
        "cases": cases,
    }
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")
    return payload


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=config.GOLDEN_FILE)
    args = parser.parse_args()
    policy_file = args.policy or latest_policy_file()
    payload = write(policy_file, args.out)
    routes = {}
    for case in payload["cases"]:
        routes[case["expected"]["route"]] = routes.get(case["expected"]["route"], 0) + 1
    print(f"wrote {len(payload['cases'])} golden vectors for {policy_file.name} ({payload['policyHash'][:18]}…): {routes}")


def latest_policy_file() -> Path:
    """The highest-versioned P002 document (the one the service treats as active)."""
    files = sorted(config.POLICY_DIR.glob("P002-assurance-v*.json"),
                   key=lambda p: [int(x) for x in p.stem.split("-v")[-1].split(".")])
    return files[-1]


if __name__ == "__main__":
    main()
